    loadLanguage() {
        const savedLang = localStorage.getItem('brics_language');
        if (savedLang && this.languages[savedLang]) {
            this.currentLanguage = savedLang;
        }
    }

    setLanguage(lang) {
        if (this.languages[lang]) {
            this.currentLanguage = lang;
            localStorage.setItem('brics_language', lang);
            // Emite um evento global para que as cenas possam reagir
            this.scene.events.emit('languageChanged');
        }
    }

    /**
     * Obtém uma string traduzida.
     * @param {string} key - A chave da string de tradução.
     * @param {object} [replaces] - Um objeto com valores para substituir placeholders. Ex: {count: 5}
     * @returns {string} A string traduzida.
     */
    get(key, replaces = {}) {
        let text = key; // Fallback para a própria chave

        if (this.languages[this.currentLanguage] && this.languages[this.currentLanguage][key]) {
            text = this.languages[this.currentLanguage][key];
        } else if (this.languages['en'] && this.languages['en'][key]) {
            // Fallback para inglês se a chave não existir no idioma atual
            text = this.languages['en'][key];
        }

        // Substitui placeholders como {count}
        for (const replaceKey in replaces) {
            text = text.replace(`{${replaceKey}}`, replaces[replaceKey]);
        }

        return text;
    }

    cycleLanguage() {
        const langKeys = Object.keys(this.languages);
        const currentIndex = langKeys.indexOf(this.currentLanguage);
        const nextIndex = (currentIndex + 1) % langKeys.length;
        this.setLanguage(langKeys[nextIndex]);
    }
